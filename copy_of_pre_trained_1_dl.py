# Dataset root path
data_root = os.path.join(path, "rsud20k")

# Load class labels
with open(os.path.join(data_root, 'classes.txt'), 'r') as f:
    class_labels = [line.strip() for line in f.readlines()]

class_label_map = {class_labels[i]: i for i in range(len(class_labels))}
