import cv2
import numpy as np
import matplotlib.pyplot as plt
import os

# Load YOLOv3 weights and configuration
def load_yolo_model():
    yolo_net = cv2.dnn.readNet("yolov3.weights", "yolov3.cfg")
    layer_names = yolo_net.getLayerNames()
    output_layers = [layer_names[i - 1] for i in yolo_net.getUnconnectedOutLayers()]
    return yolo_net, output_layers

# Load image
def load_image(image_path):
    img = cv2.imread(image_path)
    height, width, _ = img.shape
    return img, width, height

# Process image and detect objects
def detect_objects(image, yolo_net, output_layers):
    # Convert image to blob for YOLOv3
    blob = cv2.dnn.blobFromImage(image, 0.00392, (416, 416), (0, 0, 0), True, crop=False)
    yolo_net.setInput(blob)
    outputs = yolo_net.forward(output_layers)

    return outputs

# Get detected boxes, confidence, and class labels
def process_detections(outputs, height, width):
    class_ids = []
    confidences = []
    boxes = []

    for output in outputs:
        for detection in output:
            scores = detection[5:]
            class_id = np.argmax(scores)
            confidence = scores[class_id]
            if confidence > 0.5:  # Confidence threshold
                center_x = int(detection[0] * width)
                center_y = int(detection[1] * height)
                w = int(detection[2] * width)
                h = int(detection[3] * height)

                # Rectangle coordinates
                x = int(center_x - w / 2)
                y = int(center_y - h / 2)

                boxes.append([x, y, w, h])
                confidences.append(float(confidence))
                class_ids.append(class_id)

    return boxes, confidences, class_ids

# Draw bounding boxes on the image
def draw_boxes(image, boxes, confidences, class_ids, class_labels):
    indexes = cv2.dnn.NMSBoxes(boxes, confidences, 0.5, 0.4)

    for i in range(len(boxes)):
        if i in indexes:
            x, y, w, h = boxes[i]
            label = str(class_labels[class_ids[i]])
            confidence = str(round(confidences[i], 2))
            color = (0, 255, 0)
            cv2.rectangle(image, (x, y), (x + w, y + h), color, 2)
            cv2.putText(image, f"{label} {confidence}", (x, y - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.5, color, 2)

    return image

# Display Image
def display_image(image):
    plt.figure(figsize=(12, 8))
    plt.imshow(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))
    plt.axis('off')
    plt.show()

# Process a single image and save or display result
def process_single_image(image_path, yolo_net, output_layers, class_labels, save_output=True):
    img, width, height = load_image(image_path)
    outputs = detect_objects(img, yolo_net, output_layers)
    boxes, confidences, class_ids = process_detections(outputs, height, width)

    img_with_boxes = draw_boxes(img, boxes, confidences, class_ids, class_labels)

    if save_output:
        # Save the image with bounding boxes to disk
        output_path = os.path.join("output_images", os.path.basename(image_path))
        cv2.imwrite(output_path, img_with_boxes)
        print(f"Saved {output_path}")
    else:
        # Display the result
        display_image(img_with_boxes)

# Process multiple images in a folder
def process_images_in_folder(folder_path, yolo_net, output_layers, class_labels, save_output=True):
    if not os.path.exists("output_images"):
        os.makedirs("output_images")

    for filename in os.listdir(folder_path):
        if filename.endswith(".jpg") or filename.endswith(".png"):  # Process only image files
            image_path = os.path.join(folder_path, filename)
            print(f"Processing {image_path}...")
            process_single_image(image_path, yolo_net, output_layers, class_labels, save_output)

# Main function to process images in a folder
def detect_objects_in_folder(folder_path):
    yolo_net, output_layers = load_yolo_model()

    # Load the class labels (names of objects)
    with open("coco.names", "r") as f:
        class_labels = [line.strip() for line in f.readlines()]

    process_images_in_folder(folder_path, yolo_net, output_layers, class_labels, save_output=True)

