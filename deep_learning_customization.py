    def update_frame(i):
        im_display.set_array(cv2.cvtColor(images[i], cv2.COLOR_BGR2RGB))
        return [im_display]

    # Create the animation
    return animation.FuncAnimation(fig, update_frame, frames=len(images), interval=interval)

